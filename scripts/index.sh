#!/usr/bin/env bash
# Builds the router's index (skills/go/index.md) and the README skill list from each SKILL.md's
# frontmatter: skills in the order of plugin.json's skills array (else by path), grouped by area folder.
# The index leaves out the router (the model-invoked skill); the README list names it first.
# Usage: bash scripts/index.sh --write|--check [kit folder]
set -euo pipefail

mode="${1:-}"
root="$(cd "${2:-$(dirname "$0")/..}" && pwd)"
[[ "$mode" == "--write" || "$mode" == "--check" ]] || { echo "usage: index.sh --write|--check [kit folder]" >&2; exit 2; }
index="$root/skills/go/index.md"
readme="$root/README.md"

field() { # <file> <key>: the frontmatter value, surrounding quotes removed and \" unescaped
  awk -v k="$2" '
    NR == 1 && $0 != "---" { exit }
    NR > 1 && $0 == "---" { exit }
    NR > 1 && index($0, k ":") == 1 {
      v = substr($0, length(k) + 2); sub(/^[ \t]+/, "", v); sub(/[ \t]+$/, "", v)
      if (v ~ /^".*"$/) { v = substr(v, 2, length(v) - 2); gsub(/\\"/, "\"", v) }
      print v; exit
    }' "$1"
}

skill_dirs() {
  local list=""
  list="$(jq -r '.skills // [] | .[]' "$root/.claude-plugin/plugin.json" 2>/dev/null | sed 's#^\./##; s#/$##')" || true
  [[ -n "$list" ]] || list="$(cd "$root" && find skills -name SKILL.md -exec dirname {} \; | sort)"
  printf '%s\n' "$list"
}

area_of() { # skills/plan/scope -> plan; skills/go -> general
  local rel="${1#skills/}"
  [[ "$rel" == */* ]] && echo "${rel%/*}" || echo "general"
}

routed() { [[ "$(field "$1" disable-model-invocation)" != "false" ]]; }

areas() {
  local d seen=" "
  while read -r d; do
    [[ -f "$root/$d/SKILL.md" ]] && routed "$root/$d/SKILL.md" || continue
    local a; a="$(area_of "$d")"
    [[ "$seen" == *" $a "* ]] || { echo "$a"; seen+="$a "; }
  done < <(skill_dirs)
}

build_index() {
  echo "# Skill index"
  echo
  echo "Generated by \`scripts/index.sh\` from each skill's frontmatter: do not edit it by hand. Every skill but the router, by area: its command, its file, what it does and when it fits."
  local a d f
  while read -r a; do
    echo
    echo "## $a"
    echo
    while read -r d; do
      f="$root/$d/SKILL.md"
      [[ -f "$f" ]] && routed "$f" && [[ "$(area_of "$d")" == "$a" ]] || continue
      echo "- \`/my:$(field "$f" name)\` · \`$d/SKILL.md\`: $(field "$f" description) When: $(field "$f" when)"
    done < <(skill_dirs)
  done < <(areas)
}

build_list() {
  echo "<!-- skills:start: generated by scripts/index.sh from each skill's frontmatter -->"
  local a d f
  while read -r d; do
    f="$root/$d/SKILL.md"
    [[ -f "$f" ]] && ! routed "$f" || continue
    echo "- \`/my:$(field "$f" name)\`: $(field "$f" description)"
  done < <(skill_dirs)
  while read -r a; do
    echo
    echo "**$a**"
    echo
    while read -r d; do
      f="$root/$d/SKILL.md"
      [[ -f "$f" ]] && routed "$f" && [[ "$(area_of "$d")" == "$a" ]] || continue
      echo "- \`/my:$(field "$f" name)\`: $(field "$f" description)"
    done < <(skill_dirs)
  done < <(areas)
  echo "<!-- skills:end -->"
}

with_list() { # README.md with the block between the markers replaced by the file $1
  grep -q '^<!-- skills:start' "$readme" && grep -q '^<!-- skills:end' "$readme" \
    || { echo "index.sh: README.md has no <!-- skills:start --> and <!-- skills:end --> markers" >&2; return 1; }
  awk -v block="$1" '
    /^<!-- skills:start/ { while ((getline l < block) > 0) print l; skip = 1; next }
    skip && /^<!-- skills:end/ { skip = 0; next }
    !skip { print }' "$readme"
}

tmp="$(mktemp -d)"
trap 'rm -rf "$tmp"' EXIT
build_index > "$tmp/index.md"
build_list > "$tmp/list.md"
with_list "$tmp/list.md" > "$tmp/README.md"

if [[ "$mode" == "--write" ]]; then
  mkdir -p "$(dirname "$index")"
  cp "$tmp/index.md" "$index"
  cp "$tmp/README.md" "$readme"
  exit 0
fi

stale=0
cmp -s "$tmp/index.md" "$index" 2>/dev/null || { echo "index.sh: skills/go/index.md is stale: run scripts/index.sh --write" >&2; stale=1; }
cmp -s "$tmp/README.md" "$readme" || { echo "index.sh: the skill list in README.md is stale: run scripts/index.sh --write" >&2; stale=1; }
exit "$stale"
