#!/usr/bin/env bash
# A small kit, as the kit worktree of the run (./kit), and an empty data root (./kit-data).
set -euo pipefail
mkdir -p kit-data kit/.claude-plugin kit/scripts
k=kit
cat > $k/.claude-plugin/plugin.json <<'P'
{
  "name": "my",
  "version": "3.4.0",
  "description": "A personal suite of workflow skills.",
  "skills": ["./skills/go", "./skills/pr/review", "./skills/pr/sync", "./skills/improve/note"]
}
P
skill() { # <dir> <name> <description> <when> <body>
  mkdir -p "$k/$1"
  cat > "$k/$1/SKILL.md" <<P
---
name: $2
description: "$3"
disable-model-invocation: $( [[ $2 == go ]] && echo false || echo true )
when: "$4"
reads: []
---

# /my:$2

$5

Reply: $( [[ $2 == go ]] && echo "the skill it opened." || echo "what it did." )
P
}
skill skills/go go "Route a request about the kit's work to the skill that fits it, and open that skill." "any request about a pull request, a branch or the kit itself" "Read skills/go/index.md and open the skill that fits."
skill skills/pr/review review "Review a PR the way a senior colleague would: the main scenario end to end, verified findings weighed by reach and impact." "\\\"/my:review\\\", \\\"review this PR\\\"" "1. Read the PR. 2. Follow its main scenario. 3. Report findings."
skill skills/pr/sync sync "Bring the branch up to date with main safely: conflict preview, conflict classes, stops on design conflicts, regenerates generated files, runs post-merge checks, merges (never rebases) and pushes." "\\\"/my:sync\\\", \\\"merge main\\\", \\\"update the branch with main\\\"" "1. Preview conflicts. 2. Merge origin/main. 3. Run the checks. 4. Push."
skill skills/improve/note note "Log a problem with the kit, without changing anything." "\\\"/my:note <what happened>\\\", \\\"note this problem with the kit\\\"" "Append the note to the suite log."
cat > $k/skills/go/index.md <<'P'
# Skill index

Generated by `scripts/index.sh` from each skill's frontmatter: do not edit it by hand.

## pr

- `/my:review` · `skills/pr/review/SKILL.md`: Review a PR the way a senior colleague would.
- `/my:sync` · `skills/pr/sync/SKILL.md`: Bring the branch up to date with main safely.

## improve

- `/my:note` · `skills/improve/note/SKILL.md`: Log a problem with the kit, without changing anything.
P
for c in review/finds-broken-promise sync/stops-on-design-conflict note/logs-without-changing go/routes-review; do
  mkdir -p "$k/evals/$c/graders"
  printf -- '---\nmax_turns: 20\n---\n/my:%s example\n' "${c%%/*}" > "$k/evals/$c/prompt.md"
  printf -- '---\ntype: regex\ntarget: last_message\npattern: "."\n---\n' > "$k/evals/$c/graders/replies.md"
done
cat > $k/README.md <<'P'
# my

## Skills

<!-- skills:start -->
- `/my:review`: Review a PR the way a senior colleague would.
- `/my:sync`: Bring the branch up to date with main safely.
- `/my:note`: Log a problem with the kit, without changing anything.
<!-- skills:end -->
P
cat > $k/CHANGELOG.md <<'P'
# Changelog

## 3.4.0

- `/my:sync` stops on design conflicts.
P
cat > $k/scripts/check.sh <<'P'
#!/usr/bin/env bash
# The kit's checks: frontmatter, Reply line, eval folder, plugin.json entry, index line.
root="$(cd "$(dirname "$0")/.." && pwd)"; cd "$root"; errs=0
err() { echo "check.sh: $1" >&2; errs=$((errs + 1)); }
for f in $(find skills -name SKILL.md | sort); do
  d="$(dirname "$f")"; n="$(awk '/^name:/ { print $2; exit }' "$f")"
  for k in name description disable-model-invocation when reads; do grep -q "^$k:" "$f" || err "$f has no '$k'"; done
  awk 'NF { last = $0 } END { exit !(last ~ /^Reply:/) }' "$f" || err "$f does not end with a Reply: line"
  [[ -n "$(find "evals/$n" -mindepth 1 -maxdepth 1 -type d 2>/dev/null)" ]] || err "$n has no case in evals/$n/"
  grep -q "\"./$d\"" .claude-plugin/plugin.json || err "$d is not in plugin.json"
  [[ "$n" == go ]] || grep -q "$f" skills/go/index.md || err "$f is not in skills/go/index.md"
done
[[ $errs -eq 0 ]] && echo "check.sh: OK" || exit 1
P
chmod +x $k/scripts/check.sh
